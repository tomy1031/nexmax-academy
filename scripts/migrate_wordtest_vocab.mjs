/** 旧 `stagedata.js` から ステージ 3〜5 だけを 取り出す。 */
function readOldStages(path) {
  const lines = readFileSync(path, "utf8").split("\n");
  const start = lines.findIndex((line) => /^\s{4}3:\s*\{/.test(line));
  const end = lines.findIndex((line) => /^\s{4}6:\s*\{/.test(line));
  if (start < 0 || end < 0) throw new Error(`stagedata.js の 3〜5 が 見つからない: ${path}`);
  // ファイル全体は 評価できない（末尾が 欠けて いる）ので、要る ぶんだけ 包む
  const slice = lines.slice(start, end).join("\n");
  return new Function(`return {${slice}};`)();
}

/** `{表記|よみ}` を 表記に ほどき、ルビ対を 集める。 */
function unruby(text) {
  const pairs = [];
  const plain = String(text ?? "").replace(/\{([^|}]+)\|([^}]+)\}/g, (_, surface, reading) => {
    pairs.push([surface, reading]);
    return surface;
  });
  return { plain, pairs };
}

/** ローマ字から 語の id を 作る（`^[a-z0-9_-]+$`）。ぶつかったら `_2`。 */
function makeId(romaji, taken) {
  const base = String(romaji ?? "")
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, "");
  if (!base) throw new Error(`id に できる ローマ字が ない: ${romaji}`);
  if (!taken.has(base)) return base;
  for (let n = 2; ; n += 1) {
    const candidate = `${base}_${n}`;
    if (!taken.has(candidate)) return candidate;
  }
}

/** 読み辞書を 足す。同じ 表記で よみが 違う ものは 止める。 */
function mergeFurigana(existing, additions) {
  const index = new Map(existing.map(([surface, reading]) => [surface, reading]));
  const added = [];
  for (const [surface, reading] of Object.entries(additions)) {
    const found = index.get(surface);
    if (found === reading) continue;
    if (found) {
      throw new Error(`読み辞書が ぶつかる: 「${surface}」 既存 ${found} / 追加 ${reading}`);
    }
    index.set(surface, reading);
    added.push([surface, reading]);
  }
  // 長い 見出しを 先に 置く（表示は 最長一致。束の 並びは そのまま 残す）
  added.sort((a, b) => b[0].length - a[0].length);
  return { entries: [...existing, ...added], added };
}

function main() {
  const source = process.argv[2];
  if (!source) {
    console.error("使い方: node scripts/migrate_wordtest_vocab.mjs <stagedata.js のパス>");
    process.exit(1);
  }

  const old = readOldStages(source);
  const book = JSON.parse(readFileSync(VOCAB_PATH, "utf8"));
  const byTerm = new Map(book.words.map((word) => [word.term, word]));
  const byId = new Map(book.words.map((word) => [word.id, word]));
  const takenIds = new Set(byId.keys());

  const report = { added: [], reused: [], filled: [] };
  const picked = []; // { stage, oldId, vocabId }

  for (const stage of [3, 4, 5]) {
    for (const raw of old[stage].words) {
      const term = TERM_FIX[raw.id] ?? raw.ja;
      const reading = READING_FIX[raw.id] ?? raw.kana;
      const romaji = ROMAJI_FIX[raw.id] ?? raw.romaji;
      const hand = HAND[raw.id] ?? {};
      const derived = unruby(`${raw.pre}${raw.ja}${raw.post}`);
      const example = hand.ex ?? derived.plain;
      // 旧記法の ルビ対は 語の 読み辞書へ（この3ステージには 1つも 無い。他ステージ用）
      const furigana = hand.ex ? [] : derived.pairs;

      const existing = ALIAS[raw.ja] ? byId.get(ALIAS[raw.ja]) : byTerm.get(term);

      if (existing) {
        // 既存の 語は **足すだけ**。`meaningJa` など 既存の 中身は 触らない
        const filled = [];
        if (!existing.englishTerm) {
          existing.englishTerm = raw.en;
          filled.push("englishTerm");
        }
        if (!existing.wrongMeanings) {
          existing.wrongMeanings = [...raw.wrong];
          filled.push("wrongMeanings");
        }
        if (!existing.example && hand.ex) {
          existing.example = hand.ex;
          filled.push("example");
        }
        const meanings = [existing.englishTerm, ...existing.wrongMeanings].map((m) =>
          m.trim().toLowerCase(),
        );
        if (new Set(meanings).size !== meanings.length) {
          throw new Error(`選択肢が ぶつかる: ${existing.id}（${existing.term}）`);
        }
        report.reused.push(existing.id);
        if (filled.length > 0) report.filled.push(`${existing.id}(${filled.join("+")})`);
        picked.push({ stage, oldId: raw.id, vocabId: existing.id });
        continue;
      }

      if (!hand.mj) throw new Error(`meaningJa が 書かれて いない: ${raw.id} ${term}`);
      const id = makeId(romaji, takenIds);
      takenIds.add(id);
      const word = {
        id,
        term,
        reading,
        romaji,
        meaningJa: hand.mj,
        englishTerm: raw.en,
        example,
        wrongMeanings: [...raw.wrong],
      };
      if (furigana.length > 0) word.furigana = furigana;
      const meanings = [word.englishTerm, ...word.wrongMeanings].map((m) => m.trim().toLowerCase());
      if (new Set(meanings).size !== meanings.length) {
        throw new Error(`選択肢が ぶつかる: ${id}（${term}）`);
      }
      book.words.push(word);
      byTerm.set(term, word);
      byId.set(id, word);
      report.added.push(id);
      picked.push({ stage, oldId: raw.id, vocabId: id });
    }
  }

  const merged = mergeFurigana(book.furigana ?? [], FURIGANA_ADD);
  book.furigana = merged.entries;
  writeFileSync(VOCAB_PATH, `${JSON.stringify(book, null, 2)}\n`);
  console.log(
    `content/vocab/vocabulary.json（語 ${book.words.length}・読み +${merged.added.length}）`,
  );

  for (const stage of STAGES) {
    const ids = picked.filter(stage.pick).map((word) => word.vocabId);
    if (ids.length === 0) throw new Error(`語が 1つも 入らない ステージ: ${stage.id}`);
    const data = {
      kind: "wordstage",
      id: stage.id,
      title: stage.title,
      description: stage.description,
      ...(stage.label ? { label: stage.label } : {}),
      fieldSequence: FIELD_SEQUENCE,
      questionCount: ids.length, // 全問出題（台帳#110）
      passRate: PASS_RATE,
      furigana: furiganaForStage(`${stage.title} ${stage.description}`, book.furigana),
      wordIds: ids,
    };
    const path = join(ROOT, "content", "wordstages", `${stage.id}.json`);
    writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`);
    console.log(`content/wordstages/${stage.id}.json（${ids.length}語）`);
  }

  console.log(`\n新しく 足した 語: ${report.added.length}`);
  console.log(`既存を 使いまわした 語: ${report.reused.length}`);
  console.log(`既存に 欄を 足した 語: ${report.filled.length} — ${report.filled.join(" ")}`);
}

/** 見出しと 説明に 出る ぶんだけの 読み辞書を 配る（長い 見出しを 先に）。 */
function furiganaForStage(text, dictionary) {
  return dictionary
    .filter(([surface]) => text.includes(surface))
    .sort((a, b) => b[0].length - a[0].length);
}

main();
