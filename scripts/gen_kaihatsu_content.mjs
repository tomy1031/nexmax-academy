/** その文字列に 出てくる 語だけの 読み辞書（長い語を 先に）。 */
function furiganaFor(...texts) {
  const blob = texts.flat(Infinity).filter(Boolean).join(" ");
  return Object.entries(FURIGANA)
    .filter(([term]) => blob.includes(term))
    .sort((a, b) => b[0].length - a[0].length);
}

