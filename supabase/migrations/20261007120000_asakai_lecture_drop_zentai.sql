-- 朝礼の 講義（asakai_lecture）の DB行から「○○機能 全体の 進捗」の「全体の」を 外す
--
-- ## なぜ 要るか
-- 2026-10-07 の 指定「〇〇機能全体の進捗という表現は滅多に使わないので、
-- 商品一覧機能の進捗は、40％です というふうに変えたい…講義の例文もです」。
-- 合流の きまりは「同一IDなら DBが 勝つ」（設計07 §11.1）。この 教材には 2026-09-15 に
-- スタジオから 保存された DB行が あり、2026-09-29 の git の 直し（ca45a0ed）を 覆って いた。
-- 学習者には いまも「商品一覧機能 全体の 進捗は、40％です。」が 出て いる。
--
-- ## 変えるのは「機能 全体の 進捗」→「機能の 進捗」だけ（6か所）
--   ②の カードの 題「担当の 機能 全体の 進捗」（2節と 7節の 2か所）
--   ②の 例「ログイン機能 全体の 進捗は 70％です。」・3節「そして、「ログイン機能 全体の 進捗は …」」
--   7節の 型「＿＿＿＿機能 全体の 進捗は、＿＿％です。」と 例「商品一覧機能 全体の 進捗は、40％です。」
-- ほかの 文（DB行に しか ない 3節の 注意「1％ずつ こまかく 計算は しません。…」・7節の 商品一覧の 例文）
-- には 触らない。英語の 絵の 指示（prompt）は この 語を 含まない。
--
-- ## いま 流して 安全か
-- 文字を 置きかえるだけ。形（キー・並び）は 変わらない。当たる 行が 無ければ 何も しない。

update studio_contents
set
  data = replace(data::text, '機能 全体の 進捗', '機能の 進捗')::jsonb,
  updated_at = now()
where id = 'asakai_lecture'
  and kind = 'article'
  and data::text like '%機能 全体の 進捗%';
