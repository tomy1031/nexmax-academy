/**
 * 入力の 見守り — 日本語入力に なって いない ときだけ 声を かける
 *
 * クイズには `inspectReadingInput`（ローマ字の まま 打った 人に
 * 「日本語入力に かえよう」を 出し、回答を 消費しない）が あるのに、
 * ミーティングの 入力欄には 無かった。カンボジアの 教室では **IMEが 切れた まま**
 * 打ちはじめる ことが よく あり、そのまま 送ると 相手の 返事だけが 進む。
 *
 * ## ただし ミーティングは クイズと 同じ 検査を してはいけない
 * `inspectReadingInput` は「ひらがなだけ」を 求める（漢字も カタカナも 注意する）。
 * ミーティングの 答えは **漢字・カタカナ混じりが 正常**なので、あれを そのまま
 * 通すと まともな 答えの ほとんどが 引っかかる。
 * ここで 見るのは 1つだけ——**日本語の 文字が 1つも 無い**か。
 */

/** ラテン文字（半角・全角）。 */
const LATIN = /[A-Za-zＡ-Ｚａ-ｚ]/u;
/** 日本語の 文字（ひらがな・カタカナ・漢字・長音）。 */
const JAPANESE = /[ぁ-ゖァ-ヺーヽヾ㐀-鿿々〆]/u;

/**
 * 「日本語入力に なって いない」入力か。
 *
 * true になるのは **ラテン文字が あって、日本語の 文字が 1つも 無い**ときだけ。
 * 「わたしは Sopheak です。」のような 混ざった 答えは 通す——名前や 会社名を
 * ローマ字で 書くのは 正しい 日本語の 書き方で、ここで 止める 理由が 無い。
 */
export function needsJapaneseInput(raw: string): boolean {
  const text = raw.trim();
  if (text === "") return false;
  if (!LATIN.test(text)) return false;
  return !JAPANESE.test(text);
}

/* ------------------------------------------------------------------ *
 * こまった ときの 合図（「まだ 言えない」ボタンの 代わり）
 * ------------------------------------------------------------------ */

/**
 * 「むずかしいので つぎへ」と 学習者が 言った か。
 *
 * 以前は「まだ 言えない（つぎへ）」という ボタンが 画面に あった。何のための
 * ボタンか 分からない、と クライアントから 指摘が あった（2026-08-18）——
 * ボタンの 字だけでは「言えない」と「つぎへ」の 関係が 読めない。
 *
 * 代わりに **ことばで 逃げられる** ように する。実際の 会議で 使う 救援の 言い方
 *（「すみません、つぎを おねがいします」）を そのまま 練習に する ——
 * 逃げ道すら 産出に なる（設計01 P6・P10）。
 *
 * 判定は **この 端末の 中だけ**で 済ませる。AIに 聞くと、鍵の 無い 学習者だけ
 * 逃げ道が 無くなる。
 */
const GIVE_UP = [
  // 「つぎを おねがいします」「つぎに いきましょう」——**たのむ 形**のときだけ
  /つぎ(の|に|を)?\s*(おねがい|お願い|ください|下さい|いきましょう|行きましょう|いきたい)/u,
  /わかりません|分かりません|わからない|分からない/u,
  /スキップ/u,
];

/**
 * 学習者が「つぎへ 行きたい」と 言った か（言い方は いくつも 許す）。
 *
 * **「むずかしいです」は 入れない。** 4問目の しつもんは
 *「日本語の 勉強は どうですか。むずかしいですか。」で、型文の 答えが
 * まさに「すこし むずかしいです。」——ここを 逃げ道と 読むと、**正しく 答えた
 * 学習者の 答えが 捨てられ、質問が 飛ぶ**。逃げ道は 取りこぼしても 会話は
 * 止まらない（相手が 助ける）が、答えを 捨てるのは 取り返しが つかない。
 */
export function asksToSkip(raw: string): boolean {
  const text = raw.trim();
  if (text === "") return false;
  return GIVE_UP.some((pattern) => pattern.test(text));
}
