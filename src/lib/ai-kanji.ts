/** AIへの 指示に 並べる 表記の 一覧。 */
export const AI_KANJI_WORDS: readonly string[] = AI_KANJI_FURIGANA.map((entry) => entry[0]);

const KANJI = /[一-鿿々]/u;

/**
 * この 文の 漢字が **ぜんぶ 一覧の ことば**で 説明できるか。
 *
 * 一覧の 表記を 順に 取り除いて、漢字が 1つも 残らなければ よい。
 * 残った ものは ふりがなが 付かない＝学習者が そこで 止まる。
 */
export function usesOnlyAllowedKanji(text: string): boolean {
  let rest = text;
  for (const [word] of AI_KANJI_FURIGANA) {
    if (!KANJI.test(rest)) return true;
    rest = rest.split(word).join("");
  }
  return !KANJI.test(rest);
}

/** 一覧に 無い 漢字だけを 返す（言い直しを 頼む ときに 見せる）。 */
export function unknownKanji(text: string): string[] {
  let rest = text;
  for (const [word] of AI_KANJI_FURIGANA) rest = rest.split(word).join("");
  return [...new Set(rest.match(/[一-鿿々]/gu) ?? [])];
}
