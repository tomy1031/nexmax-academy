/** 台帳に 載せた 教材ごとの 聞き取り専用の 読み（かなの 語の 漢字形も 足した もの）。 */
export const LISTENING_SOUNDS_LIKE: Readonly<Record<string, readonly FuriganaEntry[]>> =
  Object.fromEntries(
    Object.entries(LEDGER).map(([id, entries]) => [id, [...entries, ...KANA_WORDS_IN_KANJI]]),
  );

/** その 教材の 聞き取り専用の 読み（無ければ 空）。 */
export function soundsLikeOf(listeningId: string): readonly FuriganaEntry[] {
  return LISTENING_SOUNDS_LIKE[listeningId] ?? [];
}
