/**
 * リスニングの 聞き取りチェック（タイピング）**だけ**が 使う 読みの 台帳
 *
 * ## なぜ 要るか（2026-09-28 の 指定）
 * 「ひらがなでも 漢字ありでも どちらも 正しく 機能するように、パターンを しっかり 登録」。
 *
 * 教材の 読み辞書（`furigana`）は **漢字の 位置からしか 引かない**（`annotateRuby`）。
 * だから「10時」「360円」「GitHub」「Slack」の ような **数字・英字で 始まる 語**は、
 * 読みを 書いても 当たらない——学習者が 聞いた とおり「じゅうじ」「ぎっとはぶ」と
 * 打つと 永久に 外れて いた。ここに 書いた 読みは **どの 位置からでも** 当たる
 *（`src/components/listening/listening-checks.ts` の `buildSoundsIndex`）。
 *
 * ## ルビは 振らない
 * 画面の 見た目は 変えない。数字に ルビを 振る 話は 別（#393）。
 *
 * ## 書きかた
 * `[表記, よみ]`。
 * - **同じ 表記を 何行でも 書ける**——2行目からは 聞こえかたの ゆれ（80％ → はちじゅっ／はちじっ）。
 * - **原稿に 無い 表記も 書ける**——学習者が 変換で 出しがちな 形（十時・80パーセント・
 *   100ギガバイト）を 読みへ 倒す。音づくりの 文字起こしも 同じ 形で 返って くる ことが ある
 *  （`scripts/lib/speech_reading.ts` も この 台帳を 通して 読みを 比べる）。
 * - 字母を 1つずつ 読む 略語（CSV・API・AWS）は 書かなくて よい（`spellLatin` が 開く）。
 *
 * ## なぜ 教材の JSON に 置かないか
 * 教材の 形（`src/content/schema.ts`）に 欄を 足すのは 共有の 変更（検問の 対象）なので、
 * 形を 変えずに 済む ように 教材の ID で 引く 台帳に した（`scripts/lib/listening_audio_plans.ts`
 * と 同じ 形）。スキーマに 欄を 足す ときは、ここの 中身を 各 教材の JSON へ 移す。
 *
 * - **漢字の 語の もう1つの 読み**も 書ける（明日 → あした／あす）。読み辞書は 1表記 1読み
 *   なので、音が どちらで 読んでも 学習者が 聞いた とおりに 打てる ように ここで 足す。
 *
 * 教材の 原稿に 出る 数字・英字が ここで 覆えて いるかは `tests/listening_sounds.test.ts` が 見張る。
 */

