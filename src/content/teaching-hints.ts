import type { PersonalityAxis, PersonalityPole } from "./personality";

/**
 * 教師の行動の向き。**減らす方向（reduce-*）は定義しない。**
 * 「指名を控える」「後回しにする」はこの学習者集団に対して構造的に有害（08 §5）。
 */
export type HintDirection = "add-choice" | "add-turn" | "add-scaffold";

export interface TeachingHint {
  readonly axis: PersonalityAxis;
  /** どちらの極が決定的なときに出すか。 */
  readonly pole: PersonalityPole;
  readonly direction: HintDirection;
  /** 教師の行動。動詞で終える。生徒が読んでも成り立つ文にする（08 §0.5）。 */
  readonly action: string;
  /** **その行動をしている最中に**観測できる、合っていないサイン（08 §2.3）。 */
  readonly counterSign: string;
}

